export type TranslationKey = keyof typeof dictionaries.en;

const localeNames: Record<Locale, string> = {
  en: "en-MY",
  ms: "ms-MY",
  "zh-CN": "zh-CN",
  ta: "ta-MY",
};

export function getLocale(value: unknown): Locale {
  return typeof value === "string" && locales.includes(value as Locale)
    ? (value as Locale)
    : "en";
}

export function translate(
  locale: Locale,
  key: TranslationKey,
  values?: Record<string, string | number>,
): string {
  let message = dictionaries[locale][key] ?? dictionaries.en[key];
  if (values) {
    for (const [name, value] of Object.entries(values)) {
      message = message.replaceAll(`{${name}}`, String(value));
    }
  }
  return message;
}

export function getMessageLocale(locale: Locale) {
  return localeNames[locale];
}

export function formatNumber(locale: Locale, value: number) {
  return new Intl.NumberFormat(getMessageLocale(locale)).format(value);
}

export function formatCurrency(locale: Locale, value: number) {
  return new Intl.NumberFormat(getMessageLocale(locale), {
    style: "currency",
    currency: "MYR",
    currencyDisplay: "code",
  }).format(value);
}

export function formatDate(locale: Locale, value: string) {
  const date = new Date(`${value}T00:00:00Z`);
  if (Number.isNaN(date.getTime())) return value;
  return new Intl.DateTimeFormat(getMessageLocale(locale), {
    dateStyle: "medium",
    timeZone: "UTC",
  }).format(date);
}

